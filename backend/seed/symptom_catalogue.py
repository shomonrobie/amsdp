"""AMSDP demo symptom catalogue — curated, bilingual, patient-reported.

What this file is
-----------------
The initial catalogue for the reception desk: a curated set of **common
patient-reported symptoms**, each with an English and a Bangla display name and
the alternate wording a receptionist might actually type.  It is seed data, not
schema: an organization's catalogue lives in ``symptom_catalog`` and can be
extended without touching this file.

What it deliberately is not
---------------------------
* **Not a scrape.**  The CARE Hospitals Bengali symptoms page
  (https://www.carehospitals.com/bn/symptoms) was consulted on 2026-11-16 as a
  *terminology reference* for common Bangla wording.  Nothing was imported
  programmatically, and the page was not treated as a symptom list: it mixes
  symptoms, diseases, investigations and departments.
* **Not a disease list.**  There is no entry for "diabetes", "typhoid",
  "anaemia" or "hypertension" — those are conditions a clinician diagnoses, not
  things a patient reports at a booking desk.  Where a patient *observes*
  something ("yellowish eyes or skin", "yellow skin"), the entry is phrased as
  the observation, not as the diagnosis it might imply.
* **Not clinically validated.**  ``REVIEW_STATUS`` below is ``"curated"``:
  reviewed for wording and for the symptom/diagnosis distinction by the AMSDP
  team, **not** signed off by a clinician.  Nothing in the UI may imply
  otherwise, and ``symptom_catalog.review_status`` carries the value on every
  row so this stays true even after the data is edited in the database.

The list is intentionally finite (~60 entries).  It covers the complaints that
dominate a Bangladeshi clinic reception — fever, cough, pain, gastric upset,
weakness, gynae and paediatric basics — without attempting to become a
terminology database.  Free-text entry exists for everything else, which is why
the catalogue does not need to be exhaustive.

``specialty_hints``
-------------------
A short list of ``specialties.code`` values this complaint is *commonly*
associated with.  It is used **only** to break ties between equally good text
matches in the browser (see ``frontend/lib/symptom-catalogue/matcher.js``).  It
never filters, never selects, and never turns a doctor's speciality into a
guess about the patient.
"""

