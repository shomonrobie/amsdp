def demo_symptom_rows(org_id):
    """The catalogue rows for one organization, ready for insertion.

    Ids are derived from the code (``demo-sym-fever``) so re-running the seed is
    idempotent and a demo link stays stable across reseeds.  ``status``,
    ``source`` and ``review_status`` are applied here rather than repeated on
    every entry above.
    """
    rows = []
    for item in DEMO_SYMPTOMS:
        row = {
            "id": "demo-sym-" + item["code"],
            "organization_id": org_id,
            "status": "active",
            "source": CATALOGUE_SOURCE,
            "review_status": REVIEW_STATUS,
        }
        row.update(item)
        rows.append(row)
    return rows

